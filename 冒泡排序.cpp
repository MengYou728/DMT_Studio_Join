#include <iostream>
using namespace std;

int main()
{
    int arr[] = { 8, 3, 6, 2, 7, 1 };
    // 自动计算数组长度，避免硬编码
    int n = sizeof(arr) / sizeof(arr[0]);

    // 冒泡排序，两层循环
    for (int i = 0; i < n - 1; i++)
    {
        // 标记本轮是否发生交换，用于提前结束
        bool swapped = false;

        for (int j = 0; j < n - 1 - i; j++)
        {
            // 前面数字比后面大就交换（升序）
            if (arr[j] > arr[j + 1])
            {
                // 使用标准库 swap，比手动 temp 更简洁
                swap(arr[j], arr[j + 1]);
                swapped = true;
            }
        }

        // 如果本轮没有交换，说明已经有序，提前退出
        if (!swapped)
            break;
    }

    // 打印最后的结果
    cout << "排序后的数字：";
    for (int i = 0; i < n; i++)
    {
        cout << arr[i] << " ";
    }
    cout << endl;

    return 0;
}
